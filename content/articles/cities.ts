import { Article, Block } from '../types';
import { art } from './_builder';
import { CITIES, City } from '../geo';
import { segmentById } from '../segments';
import { FACTS } from '../facts';

const seedOf = (s: string): number => {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
};

/** Три разных каркаса статьи. Городов много, и одинаковая структура во всех
 *  выглядела бы как штамповка — здесь она чередуется вместе с акцентом текста. */
type Shape = 'funnel' | 'channels' | 'process';
const shapeFor = (c: City): Shape => (['funnel', 'channels', 'process'] as Shape[])[seedOf(c.id) % 3];

const cityArticle = (c: City): Article => {
  const segs = c.segments.map((id) => segmentById(id)!).filter(Boolean);
  const main = segs[0];
  const second = segs[1] ?? segs[0];
  const shape = shapeFor(c);

  const common: Block[] = [
    { t: 'h2', text: `Что определяет спрос ${c.prep}` },
    { t: 'p', text: c.angle },
    { t: 'p', text: `На практике это значит, что универсальные рекламные связки здесь работают хуже локальных. Покупатель ориентируется на конкретные направления — ${c.landmarks.join(', ')} — и сравнивает варианты внутри них, а не по городу целиком.` },
    { t: 'h2', text: 'Кто конкурирует за этого клиента' },
    { t: 'p', text: `Основные игроки ${c.prep} — ${c.buyers}. Все они обращаются к одному и тому же пулу покупателей, поэтому побеждает не тот, у кого больше заявок, а тот, кто быстрее выходит на контакт и точнее попадает в запрос.` },
  ];

  const bySegment: Block[] = [
    { t: 'h2', text: `Сегменты, в которых есть спрос` },
    { t: 'ul', items: segs.map((s) => `**${s.nom}** — ${s.definition}`) },
    { t: 'p', text: `Ведущий сегмент — «${main.nom}». ${main.cycle}` },
    { t: 'h3', text: `Что подтверждать в разговоре по сегменту «${main.nom}»` },
    { t: 'ul', items: main.qualify },
    { t: 'h3', text: 'Возражения, к которым готовиться' },
    { t: 'ul', items: main.objections },
  ];

  const shapes: Record<Shape, Block[]> = {
    funnel: [
      ...common,
      { t: 'h2', text: 'Где рвётся воронка' },
      { t: 'ol', items: [
        'Заявка приходит, но первый звонок происходит через несколько часов — клиент уже говорит с конкурентом.',
        `Менеджер начинает с квалификации, которую клиент уже проходил, — раздражение и отказ.`,
        'Подбор идёт без учёта локации, а именно она определяет решение в этом городе.',
        'После первого отказа нет повторного касания — лид списывается навсегда.',
      ] },
      ...bySegment,
      { t: 'h2', text: 'Что убивает конверсию именно здесь' },
      { t: 'ul', items: main.pitfalls },
      { t: 'callout', title: 'Простая диагностика', text: 'Возьмите последние 50 заявок и посмотрите медиану времени до первого звонка. Если она больше часа, покупка новых лидов не даст прироста: проблема не в источнике.' },
    ],
    channels: [
      ...common,
      { t: 'h2', text: 'Откуда брать клиентов' },
      { t: 'table', head: ['Источник', 'Что даёт', 'Ограничение'], rows: [
        ['Рекомендации', 'Высокая конверсия', 'Объём не управляется'],
        ['Контекстная реклама', 'Сформированный спрос', 'Аукцион дорожает при росте конкуренции'],
        ['Таргет', 'Дешёвый охват', 'Длинный прогрев'],
        ['Классифайды', 'Готовый трафик', 'Клиент общается сразу с несколькими агентами'],
        ['Покупка лидов', 'Предсказуемый объём', 'Требует дисциплины обработки'],
      ] },
      { t: 'p', text: `Для ${c.gen} к этому добавляется локальный фактор: ${c.angle.charAt(0).toLowerCase()}${c.angle.slice(1)} Это меняет соотношение каналов — часть спроса приходит не изнутри города.` },
      ...bySegment,
      { t: 'h2', text: 'Как не переплатить' },
      { t: 'p', text: `Сравнивайте каналы не по цене заявки, а по стоимости сделки: цена лида ÷ сквозную конверсию. Лид за ${FACTS.primaryTiers[0].price.toLocaleString('ru-RU')} ₽ при конверсии 6% даёт сделку примерно за 60 000 ₽ — и это честная база для сравнения с любым другим источником.` },
    ],
    process: [
      ...common,
      ...bySegment,
      { t: 'h2', text: 'Регламент обработки, который работает' },
      { t: 'steps', items: [
        { title: 'Мгновенное уведомление', text: 'Заявка попадает менеджеру сразу, а не выгрузкой раз в день.' },
        { title: 'Звонок за 15 минут', text: 'Реалистичный норматив, который команда действительно соблюдает.' },
        { title: 'Сообщение при недозвоне', text: 'В тот же час: незнакомый номер часто игнорируют, сообщение читают.' },
        { title: 'Три попытки', text: 'В разные дни и время. Только после этого лид считается недоступным.' },
        { title: 'Фиксация причины', text: 'Отказ без причины делает повторное касание невозможным.' },
      ] },
      { t: 'h2', text: 'Ошибки, которые дорого стоят' },
      { t: 'ul', items: [...main.pitfalls, `Игнорирование второго по объёму сегмента — «${second.nom}»: часть клиентов приходит именно оттуда.`] },
    ],
  };

  const body: Block[] = [
    { t: 'p', text: `Разбираем, как устроен спрос на недвижимость ${c.prep}, какие сегменты дают основной объём и что нужно изменить в обработке заявок, чтобы не терять клиентов на первом контакте.` },
    ...shapes[shape],
    { t: 'h2', text: 'Если своего потока не хватает' },
    { t: 'p', text: `Покупка квалифицированных лидов закрывает разрыв между планом продаж и собственным маркетингом. Пакет стартует от ${FACTS.minPackage} лидов, передача занимает ${FACTS.transferMinutes} минут после квалификации, нецелевые заявки меняются бесплатно в течение ${FACTS.feedbackDays} дней.` },
    { t: 'cta', title: `Получать клиентов ${c.prep}`, text: 'Согласуем сегмент, локации и темп передачи под вашу команду.' },
  ];

  return art({
    slug: `klienty-na-nedvizhimost-${c.id}-kak-poluchat`,
    h1: `Как получать клиентов на недвижимость ${c.prep}`,
    title: `Как получать клиентов на недвижимость ${c.prep}: спрос, каналы, воронка`,
    description: `Разбор рынка ${c.gen}: что определяет спрос, какие сегменты дают объём, где рвётся воронка и как выстроить обработку заявок, чтобы не терять клиентов.`,
    keywords: [
      `клиенты на недвижимость ${c.nom.toLowerCase()}`,
      `где брать клиентов риелтору ${c.nom.toLowerCase()}`,
      `лиды на недвижимость ${c.nom.toLowerCase()}`,
      `продажа недвижимости ${c.nom.toLowerCase()} маркетинг`,
    ],
    category: 'Регионы',
    iso: '2026-05-06',
    lead: `${c.angle}`,
    body,
    faq: [
      { q: `Какой сегмент даёт основной объём ${c.prep}?`, a: `«${main.nom}». ${main.definition}` },
      { q: `Сколько стоит привлечь клиента ${c.prep}?`, a: `Через покупку лидов — от ${FACTS.primaryTiers[0].price.toLocaleString('ru-RU')} ₽ за заявку в зависимости от класса объекта. Через собственную рекламу цена зависит от аукциона и меняется от месяца к месяцу.` },
      { q: 'Что важнее: объём заявок или скорость обработки?', a: 'Скорость. Удвоение сквозной конверсии удешевляет сделку вдвое, а максимальная скидка за объём — только на 20%.' },
      { q: `Какие локации чаще всего фигурируют в заявках?`, a: c.landmarks.join(', ') + '.' },
    ],
    related: [`kupit-lidy-na-nedvizhimost-${c.id}`, 'skorost-pervogo-kontakta-v-nedvizhimosti', 'unit-ekonomika-pokupki-lidov-v-nedvizhimosti'],
  });
};

export const buildCityArticles = (): Article[] => CITIES.map(cityArticle);
