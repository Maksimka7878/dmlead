const buildTerm = (t: Term): Article => {
  const body: Block[] = [
    P(t.short),
    ...t.detail.map((d) => P(d)),
    H2('С чем путают'),
    UL(...t.confusion.map(([what, diff]) => `**${what}.** ${diff}`)),
    H2('Почему это влияет на деньги'),
    P(t.money),
    H2('Что с этим делать на практике'),
    OL(...t.practice),
    H2('Как термином злоупотребляют'),
    P(t.misuse),
    H2('Проверочный список'),
    UL(...t.checklist),
  ];
  if (t.example) body.push(CO('Пример', t.example));
  body.push(CTA('Обсудить работу с заявками', 'Разберём вашу воронку и посчитаем стоимость сделки.'));

  return art({
    slug: t.slug,
    h1: t.h1,
    title: `${t.h1} — определение и применение`,
    description: `${t.short} Разбираем, с чем путают термин и что с ним делать на практике.`,
    keywords: t.keywords,
    category: 'Термины',
    iso: '2026-07-28',
    lead: t.short,
    body,
    faq: [
      { q: `Что такое ${t.term.toLowerCase()}?`, a: t.short },
      { q: 'С чем чаще всего путают?', a: t.confusion.map(([w, d]) => `${w}: ${d}`).join(' ') },
      { q: 'Что делать с этим знанием?', a: t.practice[0] },
      { q: 'Как это влияет на деньги?', a: t.money },
      { q: 'На чём здесь чаще всего манипулируют?', a: t.misuse },
      { q: 'Что проверить у себя?', a: t.checklist.join('; ') + '.' },
    ],
    related: ['kupit-lidy-na-nedvizhimost', 'stoimost-lidov-na-nedvizhimost'],
  });
};

export const buildGlossaryArticles = (): Article[] => TERMS.map(buildTerm);
